def translations(language: str | None = None) -> dict:
    lang = language or get_language() or "en"
    return UR if str(lang).startswith("ur") else EN


def translate_label(value: str) -> str:
    lang = get_language() or "en"
    if str(lang).startswith("ur"):
        return LABELS_UR.get(value, value)
    return value
